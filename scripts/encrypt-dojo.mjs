#!/usr/bin/env node
/**
 * Builds public/dojo/index.html — a password gate wrapped around an encrypted
 * copy of the rule book — and the token hash the progress function checks.
 *
 * Same scheme as scripts/encrypt-plan.mjs: the plaintext lives in dojo-source/
 * (gitignored) and only ciphertext is committed.
 *
 *   DOJO_USER='…' DOJO_PASS='…' node scripts/encrypt-dojo.mjs
 *
 * Progress sync: the browser derives an API token from the decryption key
 * (SHA-256 of "dojo-api-token\n" + key). This script writes SHA-256(token) to
 * netlify/functions/dojo-progress/token-hash.mjs, so the function can check a
 * caller without the repo ever holding the token or the password. Each run
 * uses a fresh salt, so each run rotates the token; saved progress is kept.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { randomBytes, pbkdf2Sync, createCipheriv, createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// Keep in step with encrypt-plan.mjs: ~200ms on desktop, ~1s on a low-end phone.
const ITERATIONS = 2_000_000;
const TITLE = "Bhargav's Rule Book";

const user = process.env.DOJO_USER;
const pass = process.env.DOJO_PASS;

if (!user || !pass) {
  console.error('Set DOJO_USER and DOJO_PASS in the environment.');
  process.exit(1);
}

const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
if (!pkg.dependencies?.['@netlify/blobs']) {
  console.warn(
    'Warning: @netlify/blobs is not in package.json, so the progress function will not build.\n' +
    '         Run: npm install @netlify/blobs --legacy-peer-deps');
}

const content = readFileSync(resolve(root, 'dojo-source/content.html'), 'utf8');
const behaviour = readFileSync(resolve(root, 'dojo-source/behaviour.js'), 'utf8');
const template = readFileSync(resolve(root, 'scripts/dojo-gate.template.html'), 'utf8');

const salt = randomBytes(16);
const iv = randomBytes(12);

// Must mirror the browser: PBKDF2-SHA256 over "username\npassword".
const key = pbkdf2Sync(
  `${user.trim().toLowerCase()}\n${pass}`, salt, ITERATIONS, 32, 'sha256');

const cipher = createCipheriv('aes-256-gcm', key, iv);
const ciphertext = Buffer.concat([
  cipher.update(content, 'utf8'),
  cipher.final(),
  cipher.getAuthTag(), // WebCrypto expects the tag appended to the ciphertext
]);

const payload = JSON.stringify({
  v: 1,
  title: TITLE,
  iterations: ITERATIONS,
  salt: salt.toString('base64'),
  iv: iv.toString('base64'),
  data: ciphertext.toString('base64'),
});

const html = template
  .replace('__PAYLOAD__', () => payload)
  .replace('__BEHAVIOUR__', () => behaviour)
  .replace('__ITER_LABEL__', () => ITERATIONS.toLocaleString('en-US'));

mkdirSync(resolve(root, 'public/dojo'), { recursive: true });
writeFileSync(resolve(root, 'public/dojo/index.html'), html);

// Must mirror apiToken() in the gate template.
const token = createHash('sha256')
  .update(Buffer.concat([Buffer.from('dojo-api-token\n', 'utf8'), key]))
  .digest('hex');
const tokenHash = createHash('sha256').update(token, 'utf8').digest('hex');

writeFileSync(
  resolve(root, 'netlify/functions/dojo-progress/token-hash.mjs'),
  '// Generated by scripts/encrypt-dojo.mjs. SHA-256 of the progress API token.\n' +
  '// Safe to commit: the token itself is derived in the browser from the password.\n' +
  `export const TOKEN_SHA256 = '${tokenHash}';\n`);

console.log(
  `public/dojo/index.html — ${(html.length / 1024).toFixed(0)} KB ` +
  `(${(ciphertext.length / 1024).toFixed(0)} KB ciphertext, ` +
  `${ITERATIONS.toLocaleString('en-US')} PBKDF2 iterations)\n` +
  'netlify/functions/dojo-progress/token-hash.mjs — token hash updated');
